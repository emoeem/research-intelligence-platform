function normalizeLanguage(value: string | null | undefined): AppLanguage {
  if (!value) return "zh-CN";
  if (value.toLowerCase().startsWith("en")) return "en-US";
  if (value.toLowerCase().startsWith("ja")) return "ja-JP";
  return "zh-CN";
}

function detectInitialLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) return normalizeLanguage(saved);
  } catch {
    // Local storage is optional.
  }
  return "zh-CN";
}

i18n.use(initReactI18next).init({
  resources,
  lng: detectInitialLanguage(),
  fallbackLng: "zh-CN",
  supportedLngs: SUPPORTED_LANGUAGES.map((language) => language.code),
  defaultNS: "translation",
  ns: ["translation", "ui"],
  load: "currentOnly",
  returnNull: false,
  returnEmptyString: false,
  interpolation: { escapeValue: false },
  react: { useSuspense: false },
});

i18n.on("languageChanged", (language) => {
  const normalized = normalizeLanguage(language);
  if (typeof document !== "undefined") {
    document.documentElement.lang = normalized;
    document.title = i18n.t("app.title");
  }
  try {
    localStorage.setItem(STORAGE_KEY, normalized);
  } catch {
    // Language switching remains available without persistence.
  }
});

if (typeof document !== "undefined") {
  document.documentElement.lang = getAppLanguage();
  document.title = i18n.t("app.title");
}

export function translateUi(source: string): string {
  return String(
    i18n.t(source, {
      ns: "ui",
      keySeparator: false,
      defaultValue: source,
    }),
  );
}

export function useUiText(): (source: string) => string {
  const { t } = useTranslation("ui");
  return useCallback(
    (source: string) => t(source, { keySeparator: false, defaultValue: source }),
    [t],
  );
}

export async function setAppLanguage(language: AppLanguage): Promise<void> {
  await i18n.changeLanguage(language);
}

export function getAppLanguage(): AppLanguage {
  return normalizeLanguage(i18n.resolvedLanguage ?? i18n.language);
}

export default i18n;
